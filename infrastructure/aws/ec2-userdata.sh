#!/bin/bash
# MeetWave – Single EC2 instance bootstrap (~$10/month with t4g.small Spot)
# Runs the full stack (Postgres, Redis, Backend, Frontend, Nginx) via Docker Compose.
# Usage: pass as --user-data when launching an EC2 instance.

set -euxo pipefail

# ── System packages ────────────────────────────────────────────────────────────
apt-get update -y
apt-get install -y \
  git curl wget unzip \
  ca-certificates gnupg lsb-release \
  awscli

# ── Docker ─────────────────────────────────────────────────────────────────────
install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg \
  | gpg --dearmor -o /etc/apt/keyrings/docker.gpg
chmod a+r /etc/apt/keyrings/docker.gpg

echo \
  "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] \
  https://download.docker.com/linux/ubuntu $(lsb_release -cs) stable" \
  > /etc/apt/sources.list.d/docker.list

apt-get update -y
apt-get install -y docker-ce docker-ce-cli containerd.io docker-compose-plugin

systemctl enable --now docker
usermod -aG docker ubuntu

# ── Clone the repo ─────────────────────────────────────────────────────────────
REPO_URL="https://github.com/YOUR_GITHUB_USERNAME/meetwave.git"  # ← change this
APP_DIR="/opt/meetwave"

git clone "$REPO_URL" "$APP_DIR"
chown -R ubuntu:ubuntu "$APP_DIR"
cd "$APP_DIR"

# ── Pull secrets from SSM Parameter Store ─────────────────────────────────────
REGION=$(curl -s http://169.254.169.254/latest/meta-data/placement/region)

get_param() {
  aws ssm get-parameter --name "$1" --with-decryption \
    --region "$REGION" --query Parameter.Value --output text
}

cat > "$APP_DIR/.env" <<EOF
# Auto-generated by EC2 user-data – do not edit manually
POSTGRES_USER=meetwave
POSTGRES_PASSWORD=$(get_param /meetwave/db/password)
POSTGRES_DB=meetwave
POSTGRES_PORT=5432

REDIS_PASSWORD=$(get_param /meetwave/redis-password || echo "redispass")

JWT_SECRET=$(get_param /meetwave/jwt-secret)
NODE_ENV=production
PORT=4000
CORS_ORIGIN=https://$(get_param /meetwave/domain 2>/dev/null || echo "localhost")

TURN_USERNAME=turnuser
TURN_PASSWORD=$(get_param /meetwave/turn-credential)
TURN_REALM=meetwave.local
TURN_SERVER_URL=localhost
TURN_CREDENTIAL=$(get_param /meetwave/turn-credential)

NEXT_PUBLIC_API_URL=https://$(get_param /meetwave/domain 2>/dev/null || echo "localhost")/api
NEXT_PUBLIC_WS_URL=wss://$(get_param /meetwave/domain 2>/dev/null || echo "localhost")
NEXT_PUBLIC_TURN_URL=turn:$(curl -s http://169.254.169.254/latest/meta-data/public-ipv4):3478
AWS_REGION=$REGION
EOF

# ── Start services ─────────────────────────────────────────────────────────────
cd "$APP_DIR"
docker compose -f docker-compose.yml -f docker-compose.prod.yml pull || true
docker compose -f docker-compose.yml -f docker-compose.prod.yml up -d --build

# ── Wait for Postgres then run migrations ─────────────────────────────────────
sleep 30
docker compose exec -T backend npx prisma migrate deploy || true
docker compose exec -T backend npx prisma db seed        || true

# ── Install unattended-upgrades for security patches ──────────────────────────
apt-get install -y unattended-upgrades
dpkg-reconfigure -f noninteractive unattended-upgrades

echo "✅ MeetWave bootstrap complete – $(date)"
